/**
 * Build-time Medium fetch → data/articles.generated.json
 *
 * Run before `nuxt generate`. Never runs in the browser — Medium's feed sends
 * no CORS headers, which is why the old site could not do this client-side.
 *
 * data/articles.json is the source of truth and stays complete: the feed only
 * carries the latest ~10 posts, so it ENRICHES (cover image, verified date) and
 * never replaces. An article missing from the feed keeps its curated values.
 *
 * Summaries are deliberately not generated here. They are written by hand from
 * each article's content; an auto-extracted first paragraph reads like filler.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = resolve(ROOT, 'data/articles.json')
const OUT = resolve(ROOT, 'data/articles.generated.json')
const EXCERPTS = resolve(ROOT, '.data/feed-excerpts.json')
const FEED = 'https://medium.com/feed/@19it197.akashbhai.chauhan'

/**
 * Medium post IDs are the 12-hex suffix on a slug. They survive the difference
 * between a personal URL and a publication URL, and the ?source= params the
 * feed appends — so they are the only reliable join key.
 */
function postId(url) {
  const match = /-([0-9a-f]{8,16})(?:\?|$)/i.exec(url.split('?')[0])
  return match ? match[1].toLowerCase() : null
}

function unwrap(value) {
  if (!value) return null
  const cdata = /^\s*<!\[CDATA\[([\s\S]*?)\]\]>\s*$/.exec(value)
  return (cdata ? cdata[1] : value).trim()
}

function tag(block, name) {
  const match = new RegExp(`<${name}[^>]*>([\\s\\S]*?)</${name}>`).exec(block)
  return match ? unwrap(match[1]) : null
}

function parseItems(xml) {
  return xml
    .split('<item>')
    .slice(1)
    .map((chunk) => {
      const block = chunk.split('</item>')[0]
      const link = tag(block, 'link')
      if (!link) return null
      const html = tag(block, 'content:encoded') || ''
      const pubDate = tag(block, 'pubDate')
      return {
        link,
        id: postId(link),
        title: tag(block, 'title'),
        // First inline image is Medium's cover image.
        coverImage: (/<img[^>]+src="([^"]+)"/i.exec(html) || [])[1] || null,
        date: pubDate && !Number.isNaN(Date.parse(pubDate))
          ? new Date(pubDate).toISOString().slice(0, 10)
          : null,
        excerpt: html
          .replace(/<figure[\s\S]*?<\/figure>/gi, ' ')
          .replace(/<[^>]+>/g, ' ')
          .replace(/&[a-z]+;/gi, ' ')
          .replace(/\s+/g, ' ')
          .trim()
          .slice(0, 1200),
      }
    })
    .filter(Boolean)
}

async function main() {
  const source = JSON.parse(await readFile(SOURCE, 'utf8'))
  const articles = source.articles.map((a) => ({ ...a }))

  let feedItems = []
  try {
    const res = await fetch(FEED, {
      headers: { 'User-Agent': 'akash-chauhan-portfolio-build' },
    })
    if (!res.ok) throw new Error(`${res.status} ${res.statusText}`)
    feedItems = parseItems(await res.text())
    console.log(`[articles] Feed returned ${feedItems.length} posts.`)
  } catch (err) {
    console.warn(`[articles] Feed unavailable (${err.message}) — using data/articles.json as-is.`)
  }

  const feedById = new Map(feedItems.filter((i) => i.id).map((i) => [i.id, i]))
  const excerpts = {}
  let enriched = 0
  const dateConflicts = []

  for (const article of articles) {
    const id = postId(article.url)
    const match = id && feedById.get(id)
    if (!match) continue

    enriched++
    if (match.coverImage) article.coverImage = match.coverImage

    // The feed is authoritative on dates. Surface disagreements loudly —
    // wrong dates were one of the credibility problems on the old site.
    if (match.date) {
      if (article.date && article.date !== match.date) {
        dateConflicts.push(`${article.slug}: curated ${article.date} → feed ${match.date}`)
      }
      article.date = match.date
      delete article.approxDate
    }
    if (match.excerpt) excerpts[article.slug] = match.excerpt
  }

  // Newest first; undated articles sort last rather than disappearing.
  articles.sort((a, b) => (b.date || '').localeCompare(a.date || ''))

  const payload = {
    _comment:
      'Generated by scripts/fetch-articles.mjs from data/articles.json + the Medium RSS feed. Do not edit by hand — edit data/articles.json.',
    fetchedAt: new Date().toISOString(),
    source: 'Medium RSS',
    feedAvailable: feedItems.length > 0,
    total: articles.length,
    byPublication: articles.reduce((acc, a) => {
      acc[a.publication] = (acc[a.publication] || 0) + 1
      return acc
    }, {}),
    articles,
  }

  await mkdir(dirname(OUT), { recursive: true })
  await writeFile(OUT, `${JSON.stringify(payload, null, 2)}\n`, 'utf8')

  if (Object.keys(excerpts).length) {
    await mkdir(dirname(EXCERPTS), { recursive: true })
    await writeFile(EXCERPTS, `${JSON.stringify(excerpts, null, 2)}\n`, 'utf8')
  }

  if (dateConflicts.length) {
    console.warn(`[articles] Date corrections from the feed:\n  ${dateConflicts.join('\n  ')}`)
  }
  const missingSummaries = articles.filter((a) => !a.summary).length
  if (missingSummaries) {
    console.warn(`[articles] ${missingSummaries}/${articles.length} articles still need a summary.`)
  }
  console.log(
    `[articles] ${articles.length} total · ${enriched} enriched from feed · ` +
      Object.entries(payload.byPublication)
        .map(([k, v]) => `${v} ${k}`)
        .join(' · '),
  )
}

main().catch((err) => {
  console.error(`[articles] ${err.message}`)
  process.exit(1)
})
