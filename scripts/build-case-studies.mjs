/**
 * Build-time case-study index → data/case-studies.json
 *
 * The home page and /work only ever show frontmatter: title, description,
 * tags, role, client. Reading that through queryContent() pulls @nuxt/content's
 * query client into the browser bundle on a page that never queries anything at
 * runtime — it cost ~8 KB gzipped and pushed the home page over its 100 KB
 * budget.
 *
 * So the index is built here instead, the same way GitHub stats and articles
 * are. Only /work/<slug> still uses queryContent, because it renders the body.
 *
 * Deliberately a small frontmatter reader rather than a YAML dependency: the
 * fields are a known, flat set and a parser that silently accepts more than
 * that would hide mistakes in the content files.
 */

import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises'
import { resolve, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = resolve(ROOT, 'content/work')
const OUT = resolve(ROOT, 'data/case-studies.json')

/** Fields the cards render. Anything else stays in the markdown. */
const SCALARS = ['title', 'description', 'role', 'duration', 'client']
const BOOLS = ['featured', 'client_named', 'permission']
const NUMBERS = ['order']

function parseFrontmatter(src, file) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(src)
  if (!m) throw new Error(`${file}: no frontmatter`)
  const out = {}
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([a-z_]+):\s*(.*)$/i.exec(line)
    if (!kv) continue
    const [, key, rawValue] = kv
    const raw = rawValue.trim()
    if (!raw) continue

    if (SCALARS.includes(key)) {
      out[key] = raw.replace(/^['"]|['"]$/g, '')
    } else if (BOOLS.includes(key)) {
      out[key] = raw === 'true'
    } else if (NUMBERS.includes(key)) {
      out[key] = Number(raw)
    } else if (key === 'tags' && raw.startsWith('[')) {
      out[key] = raw
        .slice(1, -1)
        .split(',')
        .map((t) => t.trim().replace(/^['"]|['"]$/g, ''))
        .filter(Boolean)
    }
  }
  return out
}

const files = (await readdir(SRC)).filter((f) => f.endsWith('.md'))
const studies = []

for (const file of files) {
  const fm = parseFrontmatter(await readFile(join(SRC, file), 'utf8'), file)
  const slug = file.replace(/\.md$/, '')

  for (const required of ['title', 'description']) {
    if (!fm[required]) throw new Error(`${file}: missing "${required}"`)
  }
  // Mirrors audit check 5: a case study must state its permission position.
  if (fm.client_named === undefined || fm.permission === undefined) {
    throw new Error(`${file}: must declare client_named and permission`)
  }
  if (fm.client_named && !fm.permission) {
    throw new Error(`${file}: names a client without permission`)
  }

  studies.push({
    slug,
    path: `/work/${slug}`,
    title: fm.title,
    description: fm.description,
    tags: fm.tags || [],
    role: fm.role || null,
    client: fm.client || null,
    clientNamed: fm.client_named,
    featured: Boolean(fm.featured),
    order: fm.order ?? 99,
  })
}

studies.sort((a, b) => a.order - b.order)

await mkdir(dirname(OUT), { recursive: true })
await writeFile(
  OUT,
  `${JSON.stringify(
    {
      _comment:
        'Generated by scripts/build-case-studies.mjs from content/work/*.md frontmatter. Do not edit by hand.',
      generatedAt: new Date().toISOString(),
      studies,
    },
    null,
    2,
  )}\n`,
  'utf8',
)

console.log(
  `[case-studies] ${studies.length} indexed · ${studies.filter((s) => s.featured).length} featured · ` +
    `${studies.filter((s) => !s.clientNamed).length} anonymised`,
)
